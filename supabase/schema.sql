-- Function to generate application reference number
create or replace function public.generate_application_reference()
returns trigger
language plpgsql
as $$
declare
  year text;
  seq integer;
  new_ref text;
begin
  year := to_char(now(), 'YYYY');
  -- Get the next sequence number (you might need to create a sequence or just count)
  -- Simple loose counting for now to avoid locking issues, or use a real sequence
  select count(*) + 1 into seq from public.applications where to_char(created_at, 'YYYY') = year;
  
  new_ref := 'LGS-' || year || '-' || lpad(seq::text, 4, '0');
  NEW.reference_number := new_ref;
  return NEW;
end;
$$;

-- Trigger for reference number
create trigger set_application_reference
before insert on public.applications
for each row
when (NEW.reference_number is null)
execute function public.generate_application_reference();

