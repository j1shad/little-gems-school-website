-- Policies (Basic Setup)

-- Profiles: Users can view/edit their own profile
create policy "Users can view own profile" on public.profiles
  for select using (auth.uid() = id);

create policy "Users can update own profile" on public.profiles
  for update using (auth.uid() = id);

create policy "Users can insert own profile" on public.profiles
  for insert with check (auth.uid() = id);

-- Applications: Users can view their own applications
create policy "Users can view own applications" on public.applications
  for select using (auth.uid() = parent_id);

create policy "Users can insert own applications" on public.applications
  for insert with check (auth.uid() = parent_id);

-- Application Children: Users can view/insert children for their applications
create policy "Users can view own application children" on public.application_children
  for select using (
    exists (
      select 1 from public.applications
      where applications.id = application_children.application_id
      and applications.parent_id = auth.uid()
    )
  );

create policy "Users can insert own application children" on public.application_children
  for insert with check (
    exists (
      select 1 from public.applications
      where applications.id = application_children.application_id
      and applications.parent_id = auth.uid()
    )
  );
